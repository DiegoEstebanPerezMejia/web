-- Conserva todas las respuestas originales sin inventar existencias ni precios de venta.
CREATE TABLE IF NOT EXISTS cuestionario_proveedor (
  id_cuestionario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proveedor BIGINT NOT NULL REFERENCES proveedor(id_proveedor),
  fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  respuestas JSONB NOT NULL CHECK (jsonb_typeof(respuestas) = 'object')
);
