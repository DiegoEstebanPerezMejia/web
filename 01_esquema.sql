-- POS CONTROL ROPA | PostgreSQL 14+
-- EJECUTAR EN LA BASE pos_ropa (crearla ANTES en pgAdmin o con createdb).
-- INSTALACIÓN NUEVA; no ejecutar sobre una base MySQL previa.
-- Sin almacenes, sin SKU. CATALOGO contiene la FK id_producto.
-- Diseñado para una tienda física, prendas con talla/color y conteo de existencias.
-- NOTA: IF NOT EXISTS evita fallos al repetir CREATE, pero no migra esquemas anteriores.

BEGIN;

CREATE TABLE IF NOT EXISTS cliente (
  id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  telefono VARCHAR(25),
  correo VARCHAR(190)
);

-- Usuario de la aplicación = empleado con credenciales de acceso.
CREATE TABLE IF NOT EXISTS usuario (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  nombre_usuario VARCHAR(60) NOT NULL UNIQUE,
  correo VARCHAR(190) UNIQUE,
  hash_contrasena VARCHAR(255) NOT NULL,
  CONSTRAINT chk_usuario_sin_arroba CHECK (nombre_usuario NOT LIKE '%@%')
);

CREATE TABLE IF NOT EXISTS categoria (
  id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS proveedor (
  id_proveedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  telefono VARCHAR(25),
  correo VARCHAR(190)
);

CREATE TABLE IF NOT EXISTS metodo_pago (
  id_metodo_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE
);

-- PRODUCTO tiene los datos propios de la prenda; no tiene id_catalogo.
CREATE TABLE IF NOT EXISTS producto (
  id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_categoria BIGINT NOT NULL REFERENCES categoria(id_categoria) ON DELETE RESTRICT,
  nombre VARCHAR(160) NOT NULL,
  marca VARCHAR(120),
  descripcion VARCHAR(500),
  precio_venta NUMERIC(12,2) NOT NULL CHECK (precio_venta >= 0)
);

-- CATALOGO es el listado de productos publicados/registrados.
-- id_producto es FK y UNIQUE: una sola ficha de catálogo por producto.
-- El nombre, marca, categoría y precio se obtienen mediante JOIN a producto.
CREATE TABLE IF NOT EXISTS catalogo (
  id_catalogo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto BIGINT NOT NULL UNIQUE
    REFERENCES producto(id_producto) ON DELETE RESTRICT
);

-- No existe columna SKU. Una variante se identifica por su PK id_variante.
-- Su clave natural alternativa es (id_producto,talla,color).
-- codigo_barras es OPCIONAL y distinto de SKU; procede del primer diagrama E-R.
CREATE TABLE IF NOT EXISTS variante_producto (
  id_variante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto BIGINT NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
  codigo_barras VARCHAR(80) UNIQUE,
  talla VARCHAR(25) NOT NULL,
  color VARCHAR(60) NOT NULL,
  CONSTRAINT uq_variante_talla_color UNIQUE (id_producto, talla, color)
);

CREATE TABLE IF NOT EXISTS proveedor_producto (
  id_proveedor BIGINT NOT NULL REFERENCES proveedor(id_proveedor) ON DELETE RESTRICT,
  id_producto BIGINT NOT NULL REFERENCES producto(id_producto) ON DELETE RESTRICT,
  PRIMARY KEY (id_proveedor, id_producto)
);

-- Una sola tienda, stock por variante (talla y color), NO por almacén.
CREATE TABLE IF NOT EXISTS inventario (
  id_variante BIGINT PRIMARY KEY REFERENCES variante_producto(id_variante) ON DELETE RESTRICT,
  existencia INTEGER NOT NULL DEFAULT 0 CHECK (existencia >= 0),
  stock_minimo INTEGER NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
  stock_maximo INTEGER CHECK (stock_maximo IS NULL OR stock_maximo >= 0),
  CONSTRAINT chk_inventario_min_max CHECK (stock_maximo IS NULL OR stock_maximo >= stock_minimo)
);

CREATE TABLE IF NOT EXISTS venta (
  id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente BIGINT REFERENCES cliente(id_cliente) ON DELETE SET NULL,
  id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS compra (
  id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proveedor BIGINT NOT NULL REFERENCES proveedor(id_proveedor) ON DELETE RESTRICT,
  id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS detalle_venta (
  id_detalle_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venta BIGINT NOT NULL REFERENCES venta(id_venta) ON DELETE RESTRICT,
  id_variante BIGINT NOT NULL REFERENCES variante_producto(id_variante) ON DELETE RESTRICT,
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(12,2) NOT NULL CHECK (precio_unitario >= 0),
  CONSTRAINT uq_detalle_venta_variante UNIQUE (id_venta, id_variante)
);

CREATE TABLE IF NOT EXISTS detalle_compra (
  id_detalle_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_compra BIGINT NOT NULL REFERENCES compra(id_compra) ON DELETE RESTRICT,
  id_variante BIGINT NOT NULL REFERENCES variante_producto(id_variante) ON DELETE RESTRICT,
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  costo_unitario NUMERIC(12,2) NOT NULL CHECK (costo_unitario >= 0),
  CONSTRAINT uq_detalle_compra_variante UNIQUE (id_compra, id_variante)
);

CREATE TABLE IF NOT EXISTS pago (
  id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venta BIGINT NOT NULL REFERENCES venta(id_venta) ON DELETE RESTRICT,
  id_metodo_pago BIGINT NOT NULL REFERENCES metodo_pago(id_metodo_pago) ON DELETE RESTRICT,
  fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  monto NUMERIC(14,2) NOT NULL CHECK (monto > 0)
);

-- Folio INTERNO (no emisión de factura fiscal CFDI).
CREATE TABLE IF NOT EXISTS factura (
  id_factura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venta BIGINT NOT NULL UNIQUE REFERENCES venta(id_venta) ON DELETE RESTRICT,
  folio VARCHAR(60) NOT NULL UNIQUE,
  fecha_emision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Totales no duplicados en venta/compra.
CREATE OR REPLACE VIEW vista_venta_total AS
SELECT v.id_venta, v.id_cliente, v.id_usuario, v.fecha,
       COALESCE(SUM(d.cantidad * d.precio_unitario), 0)::NUMERIC(18,2) AS total
FROM venta v LEFT JOIN detalle_venta d ON d.id_venta = v.id_venta
GROUP BY v.id_venta, v.id_cliente, v.id_usuario, v.fecha;

CREATE OR REPLACE VIEW vista_compra_total AS
SELECT c.id_compra, c.id_proveedor, c.id_usuario, c.fecha,
       COALESCE(SUM(d.cantidad * d.costo_unitario), 0)::NUMERIC(18,2) AS total
FROM compra c LEFT JOIN detalle_compra d ON d.id_compra = c.id_compra
GROUP BY c.id_compra, c.id_proveedor, c.id_usuario, c.fecha;

-- CATALOGO.id_producto -> PRODUCTO.id_producto. La información se hereda por JOIN.
CREATE OR REPLACE VIEW vista_catalogo_prendas AS
SELECT ca.id_catalogo, p.id_producto, p.nombre AS producto,
       p.marca, p.descripcion, p.precio_venta,
       c.nombre AS categoria,
       vp.id_variante, vp.codigo_barras, vp.talla, vp.color,
       i.existencia, i.stock_minimo, i.stock_maximo
FROM catalogo ca
JOIN producto p ON p.id_producto = ca.id_producto
JOIN categoria c ON c.id_categoria = p.id_categoria
JOIN variante_producto vp ON vp.id_producto = p.id_producto
LEFT JOIN inventario i ON i.id_variante = vp.id_variante;

INSERT INTO metodo_pago (nombre)
VALUES ('Efectivo'), ('Tarjeta'), ('Transferencia')
ON CONFLICT (nombre) DO NOTHING;

COMMIT;
